Import("env")
import json
import os

# Development fallback for RP2040 images. ESP builds append the options and hardware JSON to the
# firmware image (UnifiedConfiguration.py); RP2040 images have nothing appended yet, so compile
# them in instead:
# - options: the same OPTIONS_JSON that build_flags.py builds from user_defines/super_defines
#   (domain, bind phrase UID, WiFi settings, flash-discriminator). Used where ESP reads the
#   appended options, so /options.json in LittleFS wins only when its flash-discriminator matches.
# - hardware: the JSON file named by the env option `custom_hardware_fallback`, used when
#   LittleFS has no /hardware.json.
# Replaced by configurator / UF2 config support later.
gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(gen_dir, exist_ok=True)

lines = ["// Generated by python/rp2040_config_fallback.py, do not edit", "#pragma once"]
defines = []

options = env.get("OPTIONS_JSON")
if options is not None:
    lines.append('static const char RP2040_OPTIONS_FALLBACK_JSON[] = R"elrs(%s)elrs";'
                 % json.dumps(options, separators=(",", ":")))
    defines.append("RP2040_OPTIONS_FALLBACK")

hardware_path = env.GetProjectOption("custom_hardware_fallback", None)
if hardware_path:
    with open(os.path.join(env.subst("$PROJECT_DIR"), hardware_path)) as f:
        # Parse to validate and to store it compactly
        hardware = json.dumps(json.load(f), separators=(",", ":"))
    lines.append("// from %s" % hardware_path)
    lines.append('static const char RP2040_HARDWARE_FALLBACK_JSON[] = R"elrs(%s)elrs";' % hardware)
    defines.append("RP2040_HARDWARE_FALLBACK")

header = os.path.join(gen_dir, "rp2040_config_fallback.h")
content = "\n".join(lines) + "\n"
old = open(header).read() if os.path.exists(header) else None
if old != content:
    with open(header, "w") as f:
        f.write(content)

env.Append(CPPPATH=[gen_dir], CPPDEFINES=defines)
